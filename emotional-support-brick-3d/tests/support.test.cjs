const fs=require('fs'),assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('emotional-support-brick-3d/support.html','utf8');
const dom=new JSDOM(html,{url:'https://example.org/emotional-support-brick-3d/support.html',pretendToBeVisual:true,runScripts:'dangerously'});
const w=dom.window,d=w.document,q=w.__supportQA;
assert.ok(q,'Support module initialized');
assert.ok(d.querySelector('#chat'),'Conversation log exists');
assert.equal(q.classify('I am feeling anxious today'),'worry');
assert.equal(q.classify('I have been stressed all week'),'worry');
assert.equal(q.classify('I am depressed'),'sad');
assert.equal(q.classify('I feel lonely'),'lonely');
assert.equal(q.classify('My friend died'),'grief');
assert.equal(q.classify('I feel happy'),'happy');
assert.ok(q.risk.test('I want to die'));
const counter=q.getMessageCount();
d.querySelector('#message').value='I have been feeling overwhelmed';
q.reply();
assert.ok(q.getMessageCount()>=counter+2,'Chat handled a worry message');
d.querySelector('#message').value='Can you tell me a joke?';
q.reply();
assert.match(d.querySelector('#chat').textContent,/brick|wall|builder|mortar|core|yoga|solid|stone|rock|construction/i,'Brick jokes returned');
q.crisis('I want to die right now');
assert.equal(d.querySelector('#urgent').hidden,false,'Urgent support displayed');
assert.match(d.querySelector('#urgent').textContent,/999/);
assert.ok(d.querySelector('#urgent').textContent.includes('NHS'));
d.querySelector('#clear').click();
assert.equal(d.querySelector('#urgent').hidden,true);
d.querySelector('#switch').click();
assert.equal(d.querySelector('#name').textContent,'Rusty');
assert.equal(w.sessionStorage.getItem('esb-character'),'rusty');
d.querySelector('#ground').click();
assert.equal(d.querySelector('#activity').hidden,false);
d.querySelector('#next').click();
d.querySelector('#stopExercise').click();
d.querySelector('#step').click();
assert.ok(d.querySelector('#stepInput'),'Next-step planning available');
d.querySelector('#stepInput').value='Ask a friend to chat';
d.querySelector('#stepDone').click();
assert.equal(d.querySelector('#activity').hidden,true);
assert.match(d.querySelector('#chat').textContent,/Ask a friend to chat/);
dom.window.close();
console.log('EMOTIONAL SUPPORT CHECKS PASS: dialogue, mood, jokes, crisis links, character swap, tools');
